import { test } from '@playwright/test'
import { anotar, cap, elegir, expect, login, USUARIOS } from './util'

const CU = 'CU21'

test('CU21-A notificar a un finalista de E03', async ({ page }) => {
  await login(page, USUARIOS.admin)
  await page.goto('/finalistas')
  await page.waitForTimeout(2500)
  await elegir(page, page.getByRole('combobox').first(), /E03/)
  await page.waitForTimeout(2000)
  await cap(page, CU, 'A-inicial')
  await page.getByLabel(/Seleccionar a Elena/).first().click()
  await page.getByRole('button', { name: 'Notificar seleccionados' }).click()
  const d = page.getByRole('dialog')
  await d.locator('#notificar-plazo').click()
  await page.waitForTimeout(800)
  await page.getByRole('button', { name: 'Mes siguiente' }).click()
  await page.waitForTimeout(800)
  await page.locator('button[aria-label="15 de diciembre de 2026"]').click()
  await d.locator('#notificar-lugar').fill('Oficina de la DUBSS, planta baja, de 08:00 a 12:00')
  await d.locator('#notificar-documentos').fill('Fotocopia de carnet, certificado de ingresos y boleta de luz')
  await cap(page, CU, 'A-formulario')
  await d.getByRole('button', { name: 'Enviar aviso' }).click()
  await cap(page, CU, 'A-confirmacion')
  await page.getByRole('button', { name: 'Confirmar envío' }).click()
  await page.waitForTimeout(8000)
  await cap(page, CU, 'A-final')
  anotar(CU, 'A: ventana de resultado: ' + (await page.getByRole('dialog').last().innerText()).replace(/\s+/g, ' ').slice(0, 300))
  await page.getByRole('button', { name: 'Cerrar' }).last().click()
  await page.waitForTimeout(5000)
  await cap(page, CU, 'A-final-tabla')
  anotar(CU, 'A: tabla tras el envío: ' + (await page.locator('main').innerText()).replace(/\s+/g, ' ').match(/1\s+Elena[^]*?Sin auditar/)?.[0])
  const r = await (await page.request.get('http://localhost:8025/api/v1/messages?limit=5')).json()
  anotar(CU, 'A: correos recientes en Mailpit: ' + r.messages.map((m: any) => m.Subject + ' -> ' + m.To.map((x: any) => x.Address).join(',')).join(' || '))
})

